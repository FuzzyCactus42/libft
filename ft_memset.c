#include "libft.h"

void	*ft_memset(void *s, int c, size_t n)
{
	size_t	b;
	char	*arr;

	arr = s;
	b = 0;
	while (b < n)
	{
		arr[b] = c;
		b++;
	}
	return (s);
}
